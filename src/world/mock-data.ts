export function buildCapabilityGraph(): CapabilityGraph {
  const graph = new CapabilityGraph();
  const capabilities = createMockCapabilities();
  
  capabilities.forEach(cap => {
    graph.addCapability(cap);
  });

  // Add relationships
  const whisper = graph.getCapability('speech-to-text-whisper');
  const translation = graph.getCapability('translation-marianmt');
  const tts = graph.getCapability('text-to-speech-piper');
  const llm = graph.getCapability('local-llm-llama');
  const web = graph.getCapability('web-interface-react');
  const db = graph.getCapability('database-sqlite');

  if (whisper && translation) {
    whisper.combinesWith.push(translation.id);
    translation.combinesWith.push(whisper.id);
  }
  if (whisper && tts) {
    whisper.combinesWith.push(tts.id);
    tts.combinesWith.push(whisper.id);
  }
  if (translation && tts) {
    translation.combinesWith.push(tts.id);
    tts.combinesWith.push(translation.id);
  }
  if (llm && whisper) {
    llm.combinesWith.push(whisper.id);
    whisper.combinesWith.push(llm.id);
  }
  if (web && whisper) {
    web.combinesWith.push(whisper.id);
    whisper.combinesWith.push(web.id);
  }
  if (web && db) {
    web.combinesWith.push(db.id);
    db.combinesWith.push(web.id);
  }

  return graph;
}